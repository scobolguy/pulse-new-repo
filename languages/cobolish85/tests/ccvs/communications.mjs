import { ccvsCase } from './builder.mjs';

// CCVS CM programs depend on an implementation-defined message-control system.
// These assertions validate language forms, never delivery or status semantics.
const cm = (id, ccvs, description, parts) => ccvsCase('CM', id, ccvs, description, () => ({
  ...parts, validation: 'syntax', requires: ['message-control system, configured queues, terminals and access keys']
}));
const input = `CD IN-CD FOR INPUT
    SYMBOLIC QUEUE IS MAIN-QUEUE
    SYMBOLIC SUB-QUEUE-1 IS SUB-ONE
    SYMBOLIC SUB-QUEUE-2 IS SUB-TWO
    SYMBOLIC SUB-QUEUE-3 IS SUB-THREE
    MESSAGE DATE IS ARRIVAL-DATE MESSAGE TIME IS ARRIVAL-TIME
    SYMBOLIC SOURCE IS ORIGIN TEXT LENGTH IS IN-LENGTH
    END KEY IS END-FLAG STATUS KEY IS IN-STATUS
    MESSAGE COUNT IS QUEUE-DEPTH.
01 MAIN-QUEUE PIC X(12).
01 SUB-ONE PIC X(12).
01 SUB-TWO PIC X(12).
01 SUB-THREE PIC X(12).
01 ARRIVAL-DATE PIC 9(6).
01 ARRIVAL-TIME PIC 9(8).
01 ORIGIN PIC X(12).
01 IN-LENGTH PIC 9(4).
01 END-FLAG PIC X.
01 IN-STATUS PIC XX.
01 QUEUE-DEPTH PIC 9(6).`;
const output = `CD OUT-CD FOR OUTPUT
    DESTINATION COUNT IS DEST-COUNT TEXT LENGTH IS OUT-LENGTH
    STATUS KEY IS OUT-STATUS ERROR KEY IS ERROR-FLAG
    SYMBOLIC DESTINATION IS DEST-NAME.
01 DEST-COUNT PIC 9(4) VALUE 1.
01 OUT-LENGTH PIC 9(4) VALUE 8.
01 OUT-STATUS PIC XX.
01 ERROR-FLAG PIC X.
01 DEST-NAME PIC X(12).`;
const message = '01 MESSAGE-AREA PIC X(80).\n01 ACCESS-KEY PIC X(8) VALUE "TEST-KEY".';

export const communicationCases = [
  cm('CM-INPUT-01', ['CM101M', 'CM105M'], 'Input CD metadata, subqueues, ENABLE/DISABLE, message count and RECEIVE MESSAGE', {
    ws: message,
    communicationSection: input,
    proc: `MOVE "INBOX" TO MAIN-QUEUE
ENABLE INPUT IN-CD WITH KEY ACCESS-KEY
ACCEPT IN-CD MESSAGE COUNT
RECEIVE IN-CD MESSAGE INTO MESSAGE-AREA
    NO DATA MOVE "EMPTY" TO MESSAGE-AREA
    WITH DATA CONTINUE
END-RECEIVE
DISABLE INPUT IN-CD WITH KEY ACCESS-KEY`
  }),
  cm('CM-OUTPUT-01', ['CM102M', 'CM103M', 'CM104M'], 'Output CD, symbolic destination, output terminal control and SEND WITH EMI', {
    ws: message,
    communicationSection: output,
    proc: `MOVE "TERMINAL-A" TO DEST-NAME
ENABLE OUTPUT OUT-CD WITH KEY ACCESS-KEY
SEND OUT-CD FROM MESSAGE-AREA WITH EMI
DISABLE OUTPUT OUT-CD WITH KEY ACCESS-KEY`
  }),
  cm('CM-INITIAL-INPUT-01', ['CM201M'], 'INITIAL INPUT CD, input record metadata and SEND WITH EGI', {
    ws: message,
    communicationSection: `CD IN-CD FOR INITIAL INPUT.
01 INPUT-DESCRIPTION.
   02 QUEUE-NAMES PIC X(48).
   02 ARRIVAL-DATE PIC 9(6).
   02 ARRIVAL-TIME PIC 9(8).
   02 ORIGIN PIC X(12).
   02 IN-LENGTH PIC 9(4).
   02 END-FLAG PIC X.
   02 IN-STATUS PIC XX.
   02 QUEUE-DEPTH PIC 9(6).
${output}`,
    proc: `ENABLE OUTPUT OUT-CD WITH KEY ACCESS-KEY
RECEIVE IN-CD MESSAGE INTO MESSAGE-AREA
    NO DATA CONTINUE
END-RECEIVE
SEND OUT-CD FROM MESSAGE-AREA WITH EGI
ACCEPT IN-CD MESSAGE COUNT`
  }),
  cm('CM-SEGMENTS-01', ['CM202M'], 'RECEIVE SEGMENT, SEND ESI/EMI/EGI and an identifier end indicator', {
    ws: `${message}\n01 END-INDICATOR PIC 9 VALUE 2.`,
    communicationSection: `${input}\n${output}`,
    proc: `ENABLE INPUT TERMINAL IN-CD WITH KEY ACCESS-KEY
RECEIVE IN-CD SEGMENT INTO MESSAGE-AREA
    NO DATA CONTINUE
    WITH DATA CONTINUE
END-RECEIVE
SEND OUT-CD FROM MESSAGE-AREA WITH ESI
SEND OUT-CD FROM MESSAGE-AREA WITH EMI
SEND OUT-CD FROM MESSAGE-AREA WITH EGI
SEND OUT-CD FROM MESSAGE-AREA WITH END-INDICATOR
DISABLE INPUT TERMINAL IN-CD WITH KEY ACCESS-KEY`
  }),
  cm('CM-DESTINATION-TABLE-01', ['CM202M'], 'Output destination tables, indexed destinations and multiple-recipient SEND', {
    ws: message,
    communicationSection: `CD OUT-CD FOR OUTPUT
    DESTINATION COUNT DEST-COUNT TEXT LENGTH OUT-LENGTH
    STATUS KEY OUT-STATUS
    DESTINATION TABLE OCCURS 2 TIMES INDEXED BY DEST-INDEX
    ERROR KEY ERROR-FLAG SYMBOLIC DESTINATION DEST-NAME.
01 DEST-COUNT PIC 9(4) VALUE 2.
01 OUT-LENGTH PIC 9(4) VALUE 8.
01 OUT-STATUS PIC XX.
01 ERROR-FLAG PIC X.
01 DEST-NAME PIC X(12).`,
    proc: `MOVE "TERMINAL-A" TO DEST-NAME (1)
MOVE "TERMINAL-B" TO DEST-NAME (2)
ENABLE OUTPUT OUT-CD WITH KEY ACCESS-KEY
SEND OUT-CD FROM MESSAGE-AREA WITH EMI`
  }),
  cm('CM-SEND-PURGE-01', ['CM303M', 'CM401M'], 'PURGE, SEND without FROM, CINT and REPLACING LINE forms from the flagging programs', {
    ws: message,
    communicationSection: output,
    proc: `ENABLE OUTPUT OUT-CD WITH KEY ACCESS-KEY
SEND OUT-CD FROM MESSAGE-AREA
SEND OUT-CD FROM MESSAGE-AREA WITH CINT
SEND OUT-CD WITH EMI REPLACING LINE
PURGE OUT-CD
DISABLE OUTPUT OUT-CD WITH KEY ACCESS-KEY`
  })
];
